import { writeFileSync } from 'node:fs';

const HOLIDAYS = ['2026-10-02'];
const round = (n) => Math.round(n * 100) / 100;
function rng(seed) {
  let state = seed >>> 0;
  return () => { state = (1664525 * state + 1013904223) >>> 0; return state / 4294967296; };
}
function sessionsEnding(lastDate, count) {
  const dates = [];
  const d = new Date(`${lastDate}T00:00:00.000Z`);
  while (dates.length < count) {
    const iso = d.toISOString().slice(0, 10);
    if (![0, 6].includes(d.getUTCDay()) && !HOLIDAYS.includes(iso)) dates.unshift(iso);
    d.setUTCDate(d.getUTCDate() - 1);
  }
  return dates;
}
function series(dates, seed, start) {
  const random = rng(seed);
  let price = start;
  return dates.map((date) => {
    const open = price;
    const close = open * (1 + (random() - 0.5) * 0.04);
    const high = Math.max(open, close) * (1 + random() * 0.01);
    const low = Math.min(open, close) * (1 - random() * 0.01);
    price = close;
    return { date, open: round(open), high: round(high), low: round(low), close: round(close), volume: Math.floor(10000 + random() * 90000) };
  });
}
